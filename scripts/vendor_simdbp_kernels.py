#!/usr/bin/env python3
"""Copy Parker's generated SIMDBP pack/unpack kernels into this crate.

Usage (from the root of this repo, inside WSL):

    python3 scripts/vendor_simdbp_kernels.py ~/hierarchical_pruning src/simdbp/kernels

It only READS Parker's repo. For each of his three generated files
(src/compress/simdbp_{sse2,avx2,avx512}.rs) it writes one file to the output
directory, changed in exactly these mechanical ways:

1. A provenance + license notice is put at the top.
2. Only the pack/unpack functions for bit widths 0..=8 are kept. Values in this
   crate are <= 255, so widths 9..=16 are never used. The dispatch tables
   (`PACK_FUNCS_*`, `*packblock`) are dropped; our own code picks the function.
3. The `#![rustfmt::skip]` inner attribute is removed (it needs nightly Rust);
   `src/simdbp/kernels/mod.rs` puts `#[rustfmt::skip]` on the `mod` lines instead.
4. Every `pub fn` becomes `pub unsafe fn` with
   `#[target_feature(enable = "...")]`, so the compiler is allowed to emit the
   SIMD instructions, and callers must promise (with `unsafe`) that the CPU has
   them and that the slices are long enough.

Function bodies are copied byte for byte. The script refuses to run if Parker's
repo has uncommitted changes, so the commit hash in the notice is accurate.
"""

import re
import subprocess
import sys
from pathlib import Path

# (Parker's file, our file, values per group, target features the code needs).
# The "sse2" file uses `_mm_lddqu_si128`, which is SSE3, so it needs "sse3".
# The AVX-512 file uses 16-bit shifts (`_mm512_slli_epi16`), which are AVX512BW.
FILES = [
    ("simdbp_sse2.rs", "sse3.rs", 128, "sse3"),
    ("simdbp_avx2.rs", "avx2.rs", 256, "avx2"),
    ("simdbp_avx512.rs", "avx512.rs", 512, "avx512f,avx512bw"),
]

MAX_WIDTH = 8

# One generated function: a `///` doc line, `#[inline]`, `pub fn NAME(...) {`, the
# body, and a `}` in column 0.
FUNCTION = re.compile(
    r"^(///[^\n]*\n)#\[inline\]\npub fn ((?:un)?pack(\d+)_(\d+))\((.*?)^\}\n",
    re.MULTILINE | re.DOTALL,
)


def git(repo: Path, *args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(repo), *args], check=True, capture_output=True, text=True
    ).stdout.strip()


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    repo = Path(sys.argv[1]).expanduser()
    out_dir = Path(sys.argv[2])

    if git(repo, "status", "--porcelain"):
        sys.exit(f"{repo} has uncommitted changes; refusing to vendor from it")
    commit = git(repo, "rev-parse", "HEAD")

    for src_name, dst_name, group_len, features in FILES:
        src_path = repo / "src" / "compress" / src_name
        text = src_path.read_text()
        lines = text.splitlines(keepends=True)
        assert lines[0] == "#![rustfmt::skip]\n", f"{src_name}: unexpected first line"
        generated_by = lines[1]  # "// This file is auto-generated by ..."
        assert generated_by.startswith("// This file is auto-generated"), src_name
        assert lines[2] == "use std::arch::x86_64::*;\n", src_name

        kept = []
        for m in FUNCTION.finditer(text):
            doc, name, size, width, rest = m.groups()
            assert int(size) == group_len, f"{name}: group size {size} != {group_len}"
            if int(width) > MAX_WIDTH:
                continue
            kept.append(
                f"{doc}#[inline]\n"
                f'#[target_feature(enable = "{features}")]\n'
                f"pub unsafe fn {name}({rest}}}\n"
            )
        # pack + unpack for each width 0..=8
        assert len(kept) == 2 * (MAX_WIDTH + 1), f"{src_name}: found {len(kept)} functions"

        notice = (
            "// SPDX-License-Identifier: Apache-2.0\n"
            "//\n"
            "// Copied from hierarchical_pruning by Parker Carlson\n"
            "// (https://github.com/thefxperson/hierarchical_pruning),\n"
            f"// commit {commit}, file src/compress/{src_name}.\n"
            "// Licensed under the Apache License, Version 2.0; a copy is in\n"
            "// third_party/hierarchical_pruning/LICENSE.\n"
            "//\n"
            "// MODIFIED by scripts/vendor_simdbp_kernels.py (do not edit by hand):\n"
            "// kept only bit widths 0..=8, removed the dispatch tables and the\n"
            "// `#![rustfmt::skip]` inner attribute, and turned each `pub fn` into a\n"
            f'// `pub unsafe fn` with `#[target_feature(enable = "{features}")]`.\n'
            "// Function bodies are unchanged.\n"
            "//\n"
            "// Original header:\n"
            f"{generated_by}"
            "\n"
            "use std::arch::x86_64::*;\n"
            "\n"
        )
        out_path = out_dir / dst_name
        out_path.write_text(notice + "\n".join(kept))
        print(f"wrote {out_path} ({len(kept)} functions, from {src_name} at {commit[:7]})")


if __name__ == "__main__":
    main()
